// recomp_lift_a64: AArch64 -> C++ lifter (build-time only, never linked into a game).
//   recomp_lift_a64 --image <module> --out <dir> [--files N] [--forms <dir>]
// The module's format is whichever registered image reader (program.h)
// claims it: a platform module adds its own (the Switch: NRO).
// Writes <dir>/funcs_000.cpp .. funcs_<N-1>.cpp (N fixed, default 16, so a
// build knows its outputs in advance) and <dir>/table.cpp. --forms writes
// forms.cpp and forms.txt there: one lifted function per distinct
// instruction form, for the differential test (lift_forms_test.cpp and
// oracle.py forms in platforms/horizon/tests), and forms_native.S: each form's original
// instruction in a stub that runs it on an arm64 host's own CPU.

#include <cstdio>
#include <fstream>
#include <map>
#include <string>
#include <vector>

#include "emit.h"
#include "program.h"

namespace {

using lifter::a64::Insn;
using lifter::a64::Op;

bool Write(const std::string& path, const std::string& text) {
  std::ofstream f(path, std::ios::binary);
  f << text;
  if (!f) std::fprintf(stderr, "recomp_lift_a64: cannot write %s\n", path.c_str());
  return bool(f);
}

const char* kHeader =
    "// Generated by recomp_lift_a64. Do not edit.\n#include \"a64/lifted.h\"\n\n"
    "namespace recomp::a64 {\n\n";

// Instruction forms worth running alone: everything but control flow.
bool Testable(const Insn& i) {
  switch (i.op) {
    case Op::kInvalid: case Op::kB: case Op::kBl: case Op::kBCond: case Op::kCbz: case Op::kTbz:
    case Op::kBr: case Op::kBlr: case Op::kRet: case Op::kSvc: case Op::kBrk:
      return false;
    case Op::kLdSt: case Op::kLdStPair: {
      bool wb = i.mode == lifter::a64::kPreIndex || i.mode == lifter::a64::kPostIndex;
      // Writeback onto a transferred register, and a pair load into one
      // register twice, are CONSTRAINED UNPREDICTABLE.
      if (wb && i.rn != 31 && (i.rn == i.rd || (i.op == Op::kLdStPair && i.rn == i.ra)))
        return false;
      return !(i.op == Op::kLdStPair && i.load && i.rd == i.ra);
    }
    case Op::kLdStExcl:
      return i.load || (i.rm != i.rd && i.rm != i.rn);
    default:
      return true;
  }
}

// Forms whose result does not depend on where they run or on the host's
// SP and thread pointer: those can run natively, at another address.
bool Native(const Insn& i) {
  switch (i.op) {
    case Op::kAdr: case Op::kLdLit:
      return false;
    case Op::kMrs: case Op::kMsr:
      return i.sysreg == lifter::a64::kNzcv;
    case Op::kAddImm: case Op::kAddExt:
      return i.rn != 31 && (i.setf || i.rd != 31);
    case Op::kLogImm:
      return i.setf || i.rd != 31;
    case Op::kLdSt: case Op::kLdStPair: case Op::kLdStExcl: case Op::kLdStOrder:
      return i.rn != 31;
    default:
      return true;
  }
}

bool UsesX18(const Insn& i) {
  for (int lo : {0, 5, 10, 16})
    if ((i.reg_fields & (0x1Fu << lo)) && ((i.raw >> lo) & 0x1F) == 18) return true;
  return false;
}

// The stub's frame: NativeState in platforms/horizon/tests/lift_forms.h.
std::string NativeStub(const std::string& name, uint32_t raw) {
  auto pairs = [](const char* op) {
    std::string s;
    for (int r = 0; r < 30; r += 2)
      s += std::string("  ") + op + " x" + std::to_string(r) + ", x" + std::to_string(r + 1) +
           ", [sp, #" + std::to_string(r * 8) + "]\n";
    return s;
  };
  char inst[32];
  std::snprintf(inst, sizeof inst, "  .inst 0x%08x\n", raw);
  return "  .p2align 2\n  .globl SYM(" + name + ")\nSYM(" + name + "):\n" +
         "  stp x29, x30, [sp, #-96]!\n  stp x19, x20, [sp, #16]\n  stp x21, x22, [sp, #32]\n"
         "  stp x23, x24, [sp, #48]\n  stp x25, x26, [sp, #64]\n  stp x27, x28, [sp, #80]\n"
         "  mov x1, sp\n  str x1, [x0, #264]\n  mov sp, x0\n  ldr x1, [sp, #256]\n"
         "  msr nzcv, x1\n  clrex\n" +
         pairs("ldp") + "  ldr x30, [sp, #240]\n" + inst + pairs("stp") +
         "  str x30, [sp, #240]\n  mrs x0, nzcv\n  str x0, [sp, #256]\n  ldr x0, [sp, #264]\n"
         "  mov sp, x0\n  ldp x19, x20, [sp, #16]\n  ldp x21, x22, [sp, #32]\n"
         "  ldp x23, x24, [sp, #48]\n  ldp x25, x26, [sp, #64]\n  ldp x27, x28, [sp, #80]\n"
         "  ldp x29, x30, [sp], #96\n  ret\n\n";
}

bool IsMemory(const Insn& i) {
  return i.op == Op::kLdSt || i.op == Op::kLdStPair || i.op == Op::kLdStExcl ||
         i.op == Op::kLdStOrder;
}

bool WriteForms(const lifter::a64::Program& p, const std::string& dir) {
  std::map<uint32_t, Insn> forms;  // encoding with register fields cleared
  for (const auto& [va, f] : p.functions())
    for (const auto& [iva, i] : f.insns)
      if (Testable(i)) forms.emplace(i.raw & ~i.reg_fields, i);
  std::string cpp = std::string(kHeader), table, txt, native_decls;
  std::string native =
      "// Generated by recomp_lift_a64. Do not edit.\n#ifdef __APPLE__\n#define SYM(x) _##x\n#else\n"
      "#define SYM(x) x\n#endif\n  .text\n\n";
  int n = 0;
  for (const auto& [key, i] : forms) {
    std::string name = "form_" + std::to_string(n);
    cpp += lifter::a64::EmitForm(p, i, name) + "\n";
    std::string stub = "nullptr";
    if (Native(i)) {
      native += NativeStub(name + "_native", i.raw);
      native_decls += "extern \"C\" void " + name + "_native(NativeState*);\n";
      stub = "A64_NATIVE(" + name + "_native)";
    }
    char b[200];
    std::snprintf(b, sizeof b, "  {recomp::a64::%s, %s, 0x%llXull, 0x%08Xu, \"%s\", %s},\n",
                  name.c_str(), stub.c_str(), static_cast<unsigned long long>(i.va), i.raw,
                  lifter::a64::Name(i).c_str(), UsesX18(i) ? "true" : "false");
    table += b;
    bool reg_offset = i.op == Op::kLdSt && i.mode == lifter::a64::kRegOffset;
    std::snprintf(b, sizeof b, "%d %llx %08x %s %d %d %s\n", n,
                  static_cast<unsigned long long>(i.va), i.raw, IsMemory(i) ? "mem" : "plain",
                  IsMemory(i) ? i.rn : -1, reg_offset ? i.rm : -1, lifter::a64::Name(i).c_str());
    txt += b;
    n++;
  }
  // The native stubs exist only in arm64 builds (forms_native.S).
  cpp += "}  // namespace recomp::a64\n\n#include \"lift_forms.h\"\n\n#ifdef __aarch64__\n" +
         native_decls + "#define A64_NATIVE(f) f\n#else\n#define A64_NATIVE(f) nullptr\n#endif\n\n" +
         "const Form kForms[] = {\n" + table + "};\nconst int kFormCount = " + std::to_string(n) +
         ";\n";
  std::printf("recomp_lift_a64: %d instruction forms\n", n);
  return Write(dir + "/forms.cpp", cpp) && Write(dir + "/forms.txt", txt) &&
         Write(dir + "/forms_native.S", native);
}

}  // namespace

int main(int argc, char** argv) {
  std::string image, out, forms;
  int files = 16;
  for (int i = 1; i < argc; i++) {
    std::string a = argv[i];
    auto val = [&]() -> std::string { return i + 1 < argc ? argv[++i] : ""; };
    if (a == "--image") image = val();
    else if (a == "--out") out = val();
    else if (a == "--files") files = std::stoi(val());
    else if (a == "--forms") forms = val();
    else {
      std::fprintf(stderr, "recomp_lift_a64: unknown argument %s\n", a.c_str());
      return 2;
    }
  }
  if (image.empty() || out.empty() || files < 1) {
    std::fprintf(stderr,
                 "usage: recomp_lift_a64 --image module --out dir [--files N] [--forms dir]\n");
    return 2;
  }
  lifter::a64::Program p;
  std::string err;
  if (!p.Load(image, err)) {
    std::fprintf(stderr, "recomp_lift_a64: %s\n", err.c_str());
    return 1;
  }
  p.Discover();

  // Contiguous runs of functions, balanced by instruction count.
  size_t total = 0, invalid = 0, tables = 0;
  for (const auto& [va, f] : p.functions()) {
    total += f.insns.size();
    tables += f.tables.size();
    for (const auto& [iva, i] : f.insns)
      if (i.op == Op::kInvalid) {
        invalid++;
        std::fprintf(stderr, "recomp_lift_a64: undecoded instruction %08X at %llX\n", i.raw,
                     static_cast<unsigned long long>(iva));
      }
  }
  std::vector<std::string> shard(files, kHeader);
  size_t done = 0;
  std::string decls, entries;
  for (const auto& [va, f] : p.functions()) {
    size_t k = std::min<size_t>(files - 1, done * files / std::max<size_t>(total, 1));
    shard[k] += lifter::a64::EmitFunction(p, f);
    done += f.insns.size();
    std::string name = lifter::a64::FunctionName(va);
    decls += "void " + name + "(Ctx& c);\n";
    char b[64];
    std::snprintf(b, sizeof b, "    {0x%llXull, %s},\n", static_cast<unsigned long long>(va),
                  name.c_str());
    entries += b;
  }
  char hash[32];
  std::snprintf(hash, sizeof hash, "0x%llXull",
                static_cast<unsigned long long>(p.text_hash()));
  bool ok = true;
  for (int k = 0; k < files; k++) {
    char name[32];
    std::snprintf(name, sizeof name, "/funcs_%03d.cpp", k);
    ok = Write(out + name, shard[k] + "}  // namespace recomp::a64\n") && ok;
  }
  ok = Write(out + "/table.cpp", kHeader + decls + "\nextern const LiftedFn kLiftedFunctions[] = {\n" +
                                     entries + "};\nextern const uint32_t kLiftedFunctionCount = " +
                                     std::to_string(p.functions().size()) +
                                     ";\nextern const uint64_t kLiftedTextHash = " + hash +
                                     ";\n\n}  // namespace recomp::a64\n") &&
       ok;
  if (!forms.empty()) ok = WriteForms(p, forms) && ok;
  for (const std::string& w : p.warnings())
    std::fprintf(stderr, "recomp_lift_a64: warning: %s\n", w.c_str());
  std::printf("recomp_lift_a64: %zu functions, %zu instructions, %zu jump tables, %zu undecoded\n",
              p.functions().size(), total, tables, invalid);
  return ok ? 0 : 1;
}
