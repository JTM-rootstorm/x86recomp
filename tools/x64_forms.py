#!/usr/bin/env python3
# Encodes tests/x64_isa/forms.s (Intel syntax, one instruction per line)
# into tests/x64_isa/forms.txt, the instruction list `recomp_lift --forms`
# reads: hex bytes, then the source line as a comment. Needs GNU as and
# objdump (dev time only; forms.txt is checked in).
#
#   tools/x64_forms.py [tests/x64_isa/forms.s] [tests/x64_isa/forms.txt]
import os, re, subprocess, sys, tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'tests/x64_isa/forms.s')
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, 'tests/x64_isa/forms.txt')

lines = []
for l in open(src):
    l = l.split('#')[0].strip()
    if l and not l.startswith('.'):
        lines.append(l)
with tempfile.TemporaryDirectory() as t:
    s, o = os.path.join(t, 'f.s'), os.path.join(t, 'f.o')
    open(s, 'w').write('.intel_syntax noprefix\n' + '\n'.join(lines) + '\n')
    subprocess.run(['as', '--64', '-o', o, s], check=True)
    dis = subprocess.run(['objdump', '-d', '-M', 'intel', '--insn-width=16', o],
                         capture_output=True, text=True, check=True).stdout
codes = []
for l in dis.split('\n'):
    m = re.match(r'\s*[0-9a-f]+:\t((?:[0-9a-f]{2} )+)\s*\t', l)
    if m:
        codes.append(m.group(1).strip())
if len(codes) != len(lines):
    sys.exit(f'{len(lines)} source lines but {len(codes)} instructions')
with open(dst, 'w') as f:
    f.write('# Generated by tools/x64_forms.py from forms.s. Do not edit.\n')
    for c, l in zip(codes, lines):
        f.write(f'{c:<48} # {l}\n')
print(f'{len(codes)} forms -> {dst}')
