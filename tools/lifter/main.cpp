// recomp_lift: lifts a 32-bit x86 PE (the game EXE) to C++.
//
//   recomp_lift --exe <game.exe> --symbols symbols --out generated
//            [--manifest lifter.manifest] [--insns-per-file N] [--dump VA]
//            [--x87-test OUT.cpp]   (forms for tests/lift_x87_test.cpp)
//            [--int-test OUT.cpp]   (forms for tests/lift_int_test.cpp)
//            [--module <game.dll> --symbols DIR [--manifest FILE]
//             [--base HEX]]...
//
// Each --module adds a DLL the game loads itself, lifted into the same
// output; --symbols/--manifest/--base after it apply to that DLL. DLLs
// load at their preferred base unless --base moves them (needed only when
// two modules overlap; the game's GameConfig must then give the same
// base). Their functions go into gen_<module>_NNN.cpp, the EXE's into
// gen_NNN.cpp, and table.cpp lists them all.
//
// Pass 1 discovers functions to a fixpoint (Ghidra entries + exports +
// every direct call/tail-call target found while descending). Pass 2
// rebuilds every function against the final entry set, so jumps to code
// that turned out to be an entry become tail calls consistently. Then the
// functions are emitted into generated/gen_NNN.cpp plus a table file.

#include <cctype>
#include <cstdio>
#include <deque>
#include <filesystem>
#include <fstream>
#include <map>
#include <string>
#include <vector>

#include "emit.h"
#include "function.h"
#include "program.h"
#include "x87test.h"

namespace {

void ReplaceAll(std::string& s, const std::string& from, const std::string& to) {
  size_t pos = 0;
  while ((pos = s.find(from, pos)) != std::string::npos) {
    s.replace(pos, from.size(), to);
    pos += to.size();
  }
}

// Shorten the fully qualified helper names; keeps generated files smaller
// and faster to parse.
void Shorten(std::string& s) {
  ReplaceAll(s, "::recomp::lift::", "");
  ReplaceAll(s, "::recomp::x87::", "x87::");
}

bool WriteIfChanged(const std::filesystem::path& path, const std::string& data) {
  {
    std::ifstream in(path, std::ios::binary);
    if (in) {
      std::string old((std::istreambuf_iterator<char>(in)),
                      std::istreambuf_iterator<char>());
      if (old == data) return true;  // keep mtime: no needless rebuilds
    }
  }
  std::ofstream out(path, std::ios::binary);
  out << data;
  return bool(out);
}

const char* kFilePrologue =
    "// Generated by recomp_lift. Do not edit.\n"
    "#include \"runtime/lifted.h\"\n"
    "#pragma clang diagnostic ignored \"-Wunused-label\"\n"
    "#pragma clang diagnostic ignored \"-Wunused-variable\"\n"
    "#pragma clang diagnostic ignored \"-Wunused-but-set-variable\"\n"
    "#pragma clang diagnostic ignored \"-Wparentheses-equality\"\n"
    "namespace recomp::gen {\n"
    "using namespace ::recomp::lift;\n"
    "namespace x87 = ::recomp::x87;\n";

}  // namespace

struct ModuleArgs {
  std::string path, symdir, manifest;
  uint32_t base = 0;
};

int main(int argc, char** argv) {
  std::vector<ModuleArgs> mods{{"", "symbols", "lifter.manifest", 0}};
  std::string outdir = "generated";
  uint64_t per_file = 12000;
  uint32_t dump = 0;
  std::string x87_test, int_test;
  for (int i = 1; i < argc; i++) {
    std::string a = argv[i];
    auto val = [&]() -> std::string { return i + 1 < argc ? argv[++i] : ""; };
    if (a == "--exe") mods[0].path = val();
    else if (a == "--module") mods.push_back({val(), "", "", 0});
    else if (a == "--symbols") mods.back().symdir = val();
    else if (a == "--manifest") mods.back().manifest = val();
    else if (a == "--base") mods.back().base = std::stoul(val(), nullptr, 16);
    else if (a == "--out") outdir = val();
    else if (a == "--insns-per-file") per_file = std::stoull(val());
    else if (a == "--dump") dump = std::stoul(val(), nullptr, 16);
    else if (a == "--x87-test") x87_test = val();
    else if (a == "--int-test") int_test = val();
    else {
      std::fprintf(stderr, "unknown argument %s\n", a.c_str());
      return 2;
    }
  }
  if (mods[0].path.empty()) {
    std::fprintf(stderr, "usage: recomp_lift --exe game.exe "
                         "[--symbols dir] [--out dir] "
                         "[--module game.dll --symbols dir]...\n");
    return 2;
  }

  lifter::Program p;
  std::string err;
  for (const ModuleArgs& m : mods) {
    if (m.symdir.empty()) {
      std::fprintf(stderr, "%s: --symbols missing\n", m.path.c_str());
      return 2;
    }
    if (!p.Load(m.path, m.symdir, m.base, &err)) {
      std::fprintf(stderr, "load %s: %s\n", m.path.c_str(), err.c_str());
      return 1;
    }
    if (!m.manifest.empty() && !p.LoadManifest(m.manifest, &err)) {
      std::fprintf(stderr, "manifest: %s\n", err.c_str());
      return 1;
    }
  }
  lifter::Decoder dec;

  // --int-test / --x87-test OUT: lifted instruction forms for
  // tests/lift_int_test.cpp and tests/lift_x87_test.cpp.
  if (!int_test.empty()) return lifter::WriteIntTest(p, dec, int_test, kFilePrologue);
  if (!x87_test.empty()) return lifter::WriteX87Test(p, dec, x87_test, kFilePrologue);

  // --dump VA: show decoded operands of one function, for debugging the
  // emitter against Zydis' operand model.
  if (dump) {
    lifter::Function f;
    lifter::BuildFunction(p, dec, dump, &f);
    for (const auto& [va, in] : f.insns) {
      std::printf("%08X  %-40s", va, dec.Format(in).c_str());
      for (int i = 0; i < in.d.operand_count; i++) {
        const auto& o = in.ops[i];
        std::printf(" [%d:%s%s sz%d]", i,
                    o.type == ZYDIS_OPERAND_TYPE_REGISTER   ? ZydisRegisterGetString(o.reg.value)
                    : o.type == ZYDIS_OPERAND_TYPE_MEMORY   ? "mem"
                    : o.type == ZYDIS_OPERAND_TYPE_IMMEDIATE ? "imm"
                                                             : "?",
                    i < in.d.operand_count_visible ? "" : "(h)", o.size);
      }
      std::printf("  cat=%s\n", ZydisCategoryGetString(in.d.meta.category));
    }
    lifter::Emitter em(p, dec);
    std::string code;
    std::set<uint32_t> refs;
    lifter::EmitStats st;
    em.EmitFunction(f, &code, &refs, &st);
    Shorten(code);
    std::fputs(code.c_str(), stdout);
    return 0;
  }

  // Pass 1: discovery fixpoint. Besides call/tail-call targets, any code
  // address that appears as an immediate operand (function pointers stored
  // by code) or as a dword in initialised data (vtables, callback tables)
  // becomes a weak entry (Program::weak): lifted on its own for indirect
  // calls, but code running into it from elsewhere continues inline. A
  // direct call or tail call makes it a strong entry. Only pointers into
  // the module they were found in count: an image holds no static pointers
  // into another one, so those are just numbers.
  size_t initial = p.entries.size();
  std::deque<uint32_t> work(p.entries.begin(), p.entries.end());
  std::set<uint32_t> done;
  size_t from_code_ptrs = 0, from_data_ptrs = 0;
  auto candidate = [&](const lifter::Module* m, uint32_t t, size_t* counter) {
    if (p.TextOf(t) != m || p.entries.count(t)) return;
    lifter::Insn in;
    if (!dec.Decode(p, t, &in)) return;
    p.entries.insert(t);
    p.weak.insert(t);
    work.push_back(t);
    (*counter)++;
  };
  for (const auto& m : p.modules)
    for (const auto& sec : m.img.sections) {
      if (sec.name != ".rdata" && sec.name != ".data") continue;
      for (uint32_t a = sec.va; a + 4 <= sec.va + sec.vsize; a += 4)
        candidate(&m, p.mem.read<uint32_t>(a), &from_data_ptrs);
    }
  while (!work.empty()) {
    uint32_t e = work.front();
    work.pop_front();
    if (!done.insert(e).second) continue;
    lifter::Function f;
    lifter::BuildFunction(p, dec, e, &f);
    for (const auto* s : {&f.direct_calls, &f.tail_calls})
      for (uint32_t t : *s) {
        if (!p.InText(t)) continue;
        p.weak.erase(t);  // really entered as a function
        if (p.entries.insert(t).second) work.push_back(t);
      }
    const lifter::Module* fm = p.TextOf(e);
    for (const auto& [va, in] : f.insns) {
      if (!in.ok) continue;
      for (int i = 0; i < in.d.operand_count_visible; i++)
        if (in.ops[i].type == ZYDIS_OPERAND_TYPE_IMMEDIATE &&
            !in.ops[i].imm.is_relative)
          candidate(fm, static_cast<uint32_t>(in.ops[i].imm.value.u),
                    &from_code_ptrs);
    }
  }
  std::printf("functions: %zu (%zu from Ghidra/exports, %zu discovered: "
              "%zu via code pointers, %zu via data pointers; %zu weak)\n",
              p.entries.size(), initial, p.entries.size() - initial,
              from_code_ptrs, from_data_ptrs, p.weak.size());

  // Pass 2: final CFGs and emission.
  std::filesystem::create_directories(outdir);
  lifter::Emitter em(p, dec);
  lifter::EmitStats stats;
  std::map<std::string, std::string> files;
  std::string body, report_warnings;
  std::set<uint32_t> refs;
  uint64_t file_insns = 0;
  int file_no = 0;
  // Output file names and per-module totals.
  const lifter::Module* cur = &p.modules[0];
  std::string prefix = "gen_";
  struct ModuleStats {
    uint64_t functions = 0, insns = 0;
  };
  std::map<const lifter::Module*, ModuleStats> per_module;
  auto flush = [&]() {
    if (body.empty()) return;
    std::string text = kFilePrologue;
    // Declare every referenced function, including ones defined later in
    // this file.
    for (uint32_t r : refs)
      text += "void " + lifter::FnName(r) + "(::recomp::Ctx& c);\n";
    text += "\n" + body + "}  // namespace recomp::gen\n";
    Shorten(text);
    char num[16];
    std::snprintf(num, sizeof num, "%03d.cpp", file_no++);
    files[prefix + num] = std::move(text);
    body.clear();
    refs.clear();
    file_insns = 0;
  };

  for (uint32_t e : p.entries) {
    if (const lifter::Module* m = p.TextOf(e); m && m != cur) {
      flush();
      cur = m;
      file_no = 0;
      prefix = "gen_";
      if (m != &p.modules[0]) {
        for (char ch : m->name) prefix += char(std::tolower(uint8_t(ch)));
        prefix += "_";
      }
    }
    lifter::Function f;
    lifter::BuildFunction(p, dec, e, &f);
    for (const auto& w : f.warnings) {
      char buf[32];
      std::snprintf(buf, sizeof buf, "%08X: ", e);
      report_warnings += buf + w + "\n";
    }
    uint64_t before = stats.insns;
    em.EmitFunction(f, &body, &refs, &stats);
    file_insns += stats.insns - before;
    per_module[cur].functions++;
    per_module[cur].insns += stats.insns - before;
    if (file_insns >= per_file) flush();
  }
  flush();

  // Function table for the dispatcher.
  std::string table =
      "// Generated by recomp_lift. Do not edit.\n"
      "#include \"runtime/lifted.h\"\nnamespace recomp::gen {\n";
  for (uint32_t e : p.entries)
    table += "void " + lifter::FnName(e) + "(::recomp::Ctx& c);\n";
  table += "}  // namespace recomp::gen\nnamespace recomp {\n"
           "extern const LiftedFn kLiftedFunctions[] = {\n";
  for (uint32_t e : p.entries) {
    char buf[64];
    std::snprintf(buf, sizeof buf, "  {0x%08Xu, &gen::f_%08X},\n", e, e);
    table += buf;
  }
  table += "};\nextern const uint32_t kLiftedFunctionCount = " +
           std::to_string(p.entries.size()) + ";\n}  // namespace recomp\n";
  files["table.cpp"] = table;

  // Remove stale generated files from earlier runs with more files.
  for (const auto& de : std::filesystem::directory_iterator(outdir)) {
    std::string n = de.path().filename().string();
    if (n.rfind("gen_", 0) == 0 && !files.count(n))
      std::filesystem::remove(de.path());
  }
  for (const auto& [name, text] : files)
    if (!WriteIfChanged(std::filesystem::path(outdir) / name, text)) {
      std::fprintf(stderr, "cannot write %s\n", name.c_str());
      return 1;
    }

  std::string report;
  report += "functions " + std::to_string(p.entries.size()) + "\n";
  report += "instructions " + std::to_string(stats.insns) + "\n";
  report += "files " + std::to_string(files.size()) + "\n";
  report += "unimplemented:\n";
  uint64_t unimpl = 0;
  for (const auto& [m, n] : stats.unimplemented) {
    report += "  " + m + " " + std::to_string(n) + "\n";
    unimpl += n;
  }
  report += "warnings:\n" + report_warnings;
  if (p.modules.size() > 1) {
    report += "modules:\n";
    for (const auto& m : p.modules) {
      char buf[160];
      std::snprintf(buf, sizeof buf, "  %s at %08X: %llu functions, %llu instructions\n",
                    m.name.c_str(), m.img.image_base,
                    (unsigned long long)per_module[&m].functions,
                    (unsigned long long)per_module[&m].insns);
      report += buf;
    }
  }
  WriteIfChanged(std::filesystem::path(outdir) / "lift_report.txt", report);
  std::printf("instructions: %llu, unimplemented sites: %llu, files: %zu\n",
              (unsigned long long)stats.insns, (unsigned long long)unimpl,
              files.size());
  return 0;
}
