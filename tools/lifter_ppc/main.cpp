// recomp_lift_ppc: PowerPC -> C++ lifter (build-time only, never linked into a game).
//   recomp_lift_ppc --image <module> --out <dir> [--files N] [--forms <dir>]
// The module's format is whichever registered image reader (program.h)
// claims it: a platform module adds its own (the Xbox 360: XEX).
// Writes <dir>/funcs_000.cpp .. funcs_<N-1>.cpp (N fixed, default 16, so a
// build knows its outputs in advance) and <dir>/table.cpp. --forms writes
// forms.cpp there (one lifted function per distinct instruction form, for
// the differential test in platforms/xbox360/tests), and forms_native.S
// with forms_native.c: each form's original instruction in a stub, and
// the table the PowerPC oracle program runs them from (bare metal under
// qemu-system-ppc64).

#include <cstdio>
#include <fstream>
#include <map>
#include <string>
#include <vector>

#include "emit.h"
#include "program.h"

namespace {

using lifter::ppc::Insn;
using lifter::ppc::Op;

bool Write(const std::string& path, const std::string& text) {
  std::ofstream f(path, std::ios::binary);
  f << text;
  if (!f) std::fprintf(stderr, "recomp_lift_ppc: cannot write %s\n", path.c_str());
  return bool(f);
}

const char* kHeader =
    "// Generated by recomp_lift_ppc. Do not edit.\n#include \"ppc/lifted.h\"\n\n"
    "namespace recomp::ppc {\n\n";

// Instruction forms worth running alone: everything but control flow,
// system calls and traps.
bool Testable(const Insn& i) {
  switch (i.op) {
    case Op::kInvalid: case Op::kB: case Op::kBc: case Op::kBclr: case Op::kBcctr: case Op::kSc:
    case Op::kTw: case Op::kTwi: case Op::kTd: case Op::kTdi:
      return false;
    default:
      return true;
  }
}

// How the oracle places memory operands (platforms/xbox360/tests/oracle/oracle.h,
// FormMem).
enum Mem { kNone, kDisp, kIndexed, kMultiple };
Mem MemKind(const Insn& i) {
  switch (i.op) {
    case Op::kLoad: case Op::kStore: case Op::kFpLoad: case Op::kFpStore:
      return i.indexed ? kIndexed : kDisp;
    case Op::kVload: case Op::kVstore:
      return i.opc == lifter::ppc::kVecShiftLeft || i.opc == lifter::ppc::kVecShiftRight ? kNone : kIndexed;
    case Op::kLarx: case Op::kStcx: case Op::kDcbz: return kIndexed;
    case Op::kLmw: case Op::kStmw: return kMultiple;
    default: return kNone;
  }
}
int MemSize(const Insn& i) {
  if (i.op == Op::kLmw || i.op == Op::kStmw) return 4 * (32 - i.rd);
  return i.size;
}

// The native stub keeps its state pointer in r31, so a form can run on
// the oracle CPU only if it names neither r31 nor anything the oracle
// cannot reproduce: privileged state, the time base, and DCBZ, whose block
// size on the oracle's 970 is not the Xenon's.
bool NamesR31(const Insn& i) {
  if (i.op == Op::kLmw || i.op == Op::kStmw) return true;
  // Fields in register positions that are not registers: CR fields and
  // bits, the SYNC kind, DCBZ's L, the trap condition, immediates, shifts.
  switch (i.op) {
    case Op::kCrLogic: case Op::kMcrf: case Op::kMcrxr: case Op::kSync:
    case Op::kFpArith: case Op::kFpMove: case Op::kFsel: case Op::kFcmp: case Op::kFrsp:
    case Op::kFctiw: case Op::kFcfid: case Op::kMffs: case Op::kMtfsf: case Op::kMtfsfi:
    case Op::kMtfsb: case Op::kMcrfs:
      return false;  // no general registers
    case Op::kFpLoad: case Op::kFpStore:
      return i.ra == 31 || (i.indexed && i.rb == 31);  // RT/RS is an FPR
    case Op::kVmx: case Op::kVcmp: case Op::kMfvscr: case Op::kMtvscr:
      return false;
    case Op::kVload: case Op::kVstore:
      return i.ra == 31 || i.rb == 31;
    default:
      break;
  }
  bool rd = !(i.op == Op::kCmp || i.op == Op::kCmpl || i.op == Op::kCmpi || i.op == Op::kCmpli ||
              i.op == Op::kCacheHint || i.op == Op::kDcbz);
  bool rb = (i.raw >> 26) == 31 || i.op == Op::kRlwnm || i.op == Op::kRldcl || i.op == Op::kRldcr;
  if (i.op == Op::kSrawi || i.op == Op::kSradi) rb = false;
  return (rd && i.rd == 31) || i.ra == 31 || (rb && i.rb == 31);
}

// The VMX code a VMX128 form runs as on the oracle, which has only VMX:
// the same operation and operands in VMX's encoding, or for three of
// VMX128's own operations a sequence of VMX ones through v30, v31 and r0,
// which the stub then reloads from the state (so these forms must not
// name them), with its constant in `data`. Empty where there is none.
struct Twin {
  std::string code, data;
  bool scratch = false;
};
Twin TwinOf(const Insn& i, const std::string& name) {
  using namespace recomp::ppc;
  char b[256];
  if (uint32_t raw = lifter::ppc::VmxEncoding(i)) {
    std::snprintf(b, sizeof b, "  .long 0x%08x\n", raw);
    return {b, ""};
  }
  if (i.op != Op::kVmx || i.rd >= 30 || i.ra >= 30 || i.rb >= 30) return {};
  const std::string k = name + "_k";
  const std::string load = "  lis 0, " + k + "@h\n  ori 0, 0, " + k + "@l\n";
  uint32_t w[4];
  switch (i.opc) {
    case kVmulfp128:  // vA * vB + -0.0, exactly vA * vB
      std::snprintf(b, sizeof b, "  vspltisw 31, -1\n  vslw 31, 31, 31\n  vmaddfp %d, %d, %d, 31\n", i.rd, i.ra, i.rb);
      return {b, "", true};
    case kVrlimi128:  // rotate by octets, select the words
      for (int e = 0; e < 4; e++) w[e] = (i.imm >> (3 - e)) & 1 ? ~0u : 0u;
      std::snprintf(b, sizeof b, "  vsldoi 31, %d, %d, %d\n%s  lvx 30, 0, 0\n  vsel %d, %d, 31, 30\n", i.rb, i.rb,
                    int(4 * (i.imm >> 4)), load.c_str(), i.rd, i.rd);
      break;
    case kVpermwi128:  // the bytes of the chosen words
      for (int e = 0; e < 4; e++) {
        uint32_t s = 4 * ((i.imm >> (6 - 2 * e)) & 3);
        w[e] = s << 24 | (s + 1) << 16 | (s + 2) << 8 | (s + 3);
      }
      std::snprintf(b, sizeof b, "%s  lvx 31, 0, 0\n  vperm %d, %d, %d, 31\n", load.c_str(), i.rd, i.rb, i.rb);
      break;
    default:
      return {};
  }
  char d[160];
  std::snprintf(d, sizeof d, "  .p2align 4\n%s:\n  .long 0x%08x, 0x%08x, 0x%08x, 0x%08x\n", k.c_str(), w[0], w[1],
                w[2], w[3]);
  return {b, d, true};
}

bool Native(const Insn& i) {
  if (lifter::ppc::IsVmx128(i.raw) && TwinOf(i, "").code.empty()) return false;
  switch (i.op) {
    case Op::kMftb: case Op::kMfmsr: case Op::kMtmsr: case Op::kMtmsrd: case Op::kDcbz:
      return false;
    // The LVLX family is the Xenon's (and Cell's), not the 970's.
    case Op::kVload: case Op::kVstore:
      if (i.opc == lifter::ppc::kVecLeft || i.opc == lifter::ppc::kVecRight) return false;
      break;
    case Op::kMfspr: case Op::kMtspr:
      return i.spr == lifter::ppc::kXer || i.spr == lifter::ppc::kLr || i.spr == lifter::ppc::kCtr;
    default:
      break;
  }
  // An absolute address (RA = 0 with a displacement) is outside the buffer.
  if (MemKind(i) == kDisp && i.ra == 0) return false;
  return !NamesR31(i);
}

// The stub's frame and the state it runs from (NativeState in
// platforms/xbox360/tests/oracle/oracle.h), around `code`.
std::string NativeStub(const std::string& name, const std::string& code) {
  std::string s = "  .p2align 2\n  .globl " + name + "\n" + name + ":\n";
  s += "  mflr 0\n  std 0, 16(1)\n  stdu 1, -320(1)\n  std 2, 32(1)\n";
  for (int r = 13; r < 32; r++) s += "  std " + std::to_string(r) + ", " + std::to_string(40 + 8 * (r - 13)) + "(1)\n";
  s += "  mfcr 0\n  std 0, 200(1)\n  std 1, 288(3)\n  mr 31, 3\n";
  s += "  ld 0, 256(31)\n  mtcrf 255, 0\n  ld 0, 264(31)\n  mtxer 0\n  ld 0, 272(31)\n  mtlr 0\n"
       "  ld 0, 280(31)\n  mtctr 0\n";
  // FPSCR (and what it became: MTFSF computes the summaries), then the FPRs.
  s += "  lfd 0, 552(31)\n  mtfsf 255, 0\n  mffs 0\n  stfd 0, 560(31)\n";
  for (int r = 0; r < 32; r++) s += "  lfd " + std::to_string(r) + ", " + std::to_string(296 + 8 * r) + "(31)\n";
  // VSCR (and what it became), then the vector registers, r0 as the index.
  s += "  li 0, 1088\n  lvx 0, 31, 0\n  mtvscr 0\n  mfvscr 0\n  li 0, 1104\n  stvx 0, 31, 0\n";
  for (int r = 0; r < 32; r++) s += "  li 0, " + std::to_string(576 + 16 * r) + "\n  lvx " + std::to_string(r) + ", 31, 0\n";
  for (int r = 0; r < 31; r++) s += "  ld " + std::to_string(r) + ", " + std::to_string(8 * r) + "(31)\n";
  s += code;
  for (int r = 0; r < 31; r++) s += "  std " + std::to_string(r) + ", " + std::to_string(8 * r) + "(31)\n";
  for (int r = 0; r < 32; r++) s += "  stfd " + std::to_string(r) + ", " + std::to_string(296 + 8 * r) + "(31)\n";
  s += "  mffs 0\n  stfd 0, 552(31)\n";
  for (int r = 0; r < 32; r++) s += "  li 0, " + std::to_string(576 + 16 * r) + "\n  stvx " + std::to_string(r) + ", 31, 0\n";
  s += "  mfvscr 0\n  li 0, 1088\n  stvx 0, 31, 0\n";
  s += "  mfcr 0\n  std 0, 256(31)\n  mfxer 0\n  std 0, 264(31)\n  mflr 0\n  std 0, 272(31)\n"
       "  mfctr 0\n  std 0, 280(31)\n  ld 1, 288(31)\n  ld 2, 32(1)\n";
  for (int r = 13; r < 32; r++) s += "  ld " + std::to_string(r) + ", " + std::to_string(40 + 8 * (r - 13)) + "(1)\n";
  s += "  ld 0, 200(1)\n  mtcrf 255, 0\n  addi 1, 1, 320\n  ld 0, 16(1)\n  mtlr 0\n  blr\n\n";
  return s;
}

bool WriteForms(const lifter::ppc::Program& p, const std::string& dir) {
  // One example per form: the encoding with its register fields cleared,
  // and for the D and DS forms its immediate too; an example the oracle can
  // run is preferred.
  std::map<uint32_t, Insn> forms;
  for (const auto& [va, f] : p.functions())
    for (const auto& [iva, i] : f.insns) {
      if (!Testable(i)) continue;
      uint32_t primary = i.raw >> 26;
      bool fields = primary == 19 || primary == 20 || primary == 21 || primary == 23 ||
                    primary == 30 || primary == 31;
      uint32_t key = fields ? i.raw & ~0x03FFF800u : i.raw & 0xFC000003u;
      // Floating point: the extended opcode and Rc (A forms: bits 26-31;
      // X forms: 21-31), without the FPR fields.
      if (primary == 59 || primary == 63)
        key = i.op == Op::kFpArith || i.op == Op::kFsel ? i.raw & 0xFC00003Fu : i.raw & 0xFC0007FFu;
      // VMX: VA forms by bits 26-31, VC and VX forms by 21-31; the
      // operations with an immediate in a register field keep it.
      if (primary == 4) {
        key = i.raw & 0x20 ? i.raw & 0xFC00003Fu : i.raw & 0xFC0007FFu;
        switch (i.opc) {
          case recomp::ppc::kVsldoi: key |= i.raw & 0x000003C0u; break;
          case recomp::ppc::kVspltb: case recomp::ppc::kVsplth: case recomp::ppc::kVspltw:
          case recomp::ppc::kVspltisb: case recomp::ppc::kVspltish: case recomp::ppc::kVspltisw:
          case recomp::ppc::kVcfux: case recomp::ppc::kVcfsx: case recomp::ppc::kVctuxs:
          case recomp::ppc::kVctsxs:
            key |= i.raw & 0x001F0000u;
            break;
          default:
            break;
        }
      }
      // VMX128: without the bits that only name registers (flipping one
      // decodes to the same operation and immediate).
      if (lifter::ppc::IsVmx128(i.raw)) {
        key = i.raw;
        for (int b = 0; b < 26; b++) {
          Insn f = lifter::ppc::Decode(i.va, i.raw ^ (1u << b));
          if (f.op == i.op && f.opc == i.opc && f.imm == i.imm && f.rc == i.rc && f.size == i.size)
            key &= ~(1u << b);
        }
      }
      // Where those bits are not registers: the SPR, the SYNC kind, DCBZ's
      // size, and the compares' L bit.
      switch (i.op) {
        case Op::kMfspr: case Op::kMtspr: case Op::kMftb: case Op::kSync: case Op::kDcbz:
        case Op::kMtfsf: case Op::kMtfsfi: case Op::kMtfsb: case Op::kMcrfs:
          key = i.raw;
          break;
        case Op::kCmp: case Op::kCmpl: case Op::kCmpi: case Op::kCmpli:
          key |= i.raw & 0x00200000u;
          break;
        default:
          break;
      }
      auto [it, added] = forms.emplace(key, i);
      if (!added && !Native(it->second) && Native(i)) it->second = i;
    }
  std::string cpp = kHeader, table, native = "// Generated by recomp_lift_ppc. Do not edit.\n  .text\n\n", data;
  std::string oracle =
      "// Generated by recomp_lift_ppc. Do not edit.\n#include \"oracle.h\"\n\n";
  std::string oracle_table;
  int n = 0, natives = 0;
  for (const auto& [key, i] : forms) {
    std::string name = "form_" + std::to_string(n);
    cpp += lifter::ppc::EmitForm(p, i, name) + "\n";
    char b[256];
    std::snprintf(b, sizeof b, "  {recomp::ppc::%s, 0x%llXull, 0x%08Xu, \"%s\"},\n", name.c_str(),
                  static_cast<unsigned long long>(i.va), i.raw, lifter::ppc::Name(i).c_str());
    table += b;
    std::string stub = "0";
    if (Native(i)) {
      Twin twin = lifter::ppc::IsVmx128(i.raw) ? TwinOf(i, name) : Twin{};
      if (twin.code.empty()) {
        char inst[32];
        std::snprintf(inst, sizeof inst, "  .long 0x%08x\n", i.raw);
        twin.code = inst;
      } else if (twin.scratch) {
        // Reload what the sequence used.
        twin.code += "  li 0, 1056\n  lvx 30, 31, 0\n  li 0, 1072\n  lvx 31, 31, 0\n  ld 0, 0(31)\n";
        data += twin.data;
      }
      native += NativeStub(name + "_native", twin.code);
      oracle += "void " + name + "_native(struct NativeState*);\n";
      stub = name + "_native";
      natives++;
    }
    bool aligned = i.op == Op::kLarx || i.op == Op::kStcx || MemKind(i) == kMultiple;
    std::snprintf(b, sizeof b, "  {%s, 0x%08Xu, %d, %d, %d, %d, %lld, %d},\n", stub.c_str(), i.raw,
                  int(MemKind(i)), i.ra, i.rb, MemSize(i), static_cast<long long>(i.imm),
                  aligned ? 1 : 0);
    oracle_table += b;
    n++;
  }
  cpp += "}  // namespace recomp::ppc\n\n#include \"lift_forms.h\"\n\nconst Form kForms[] = {\n" + table +
         "};\nconst int kFormCount = " + std::to_string(n) + ";\n";
  oracle += "\nconst struct FormInfo kFormInfo[] = {\n" + oracle_table +
            "};\nconst int kFormInfoCount = " + std::to_string(n) + ";\n";
  std::printf("recomp_lift_ppc: %d instruction forms, %d run on the oracle\n", n, natives);
  if (!data.empty()) native += "  .section .rodata\n" + data;
  return Write(dir + "/forms.cpp", cpp) && Write(dir + "/forms_native.S", native) &&
         Write(dir + "/forms_native.c", oracle);
}

}  // namespace

int main(int argc, char** argv) {
  std::string image, out, forms;
  int files = 16;
  for (int i = 1; i < argc; i++) {
    std::string a = argv[i];
    auto val = [&]() -> std::string { return i + 1 < argc ? argv[++i] : ""; };
    if (a == "--image") image = val();
    else if (a == "--out") out = val();
    else if (a == "--files") files = std::stoi(val());
    else if (a == "--forms") forms = val();
    else {
      std::fprintf(stderr, "recomp_lift_ppc: unknown argument %s\n", a.c_str());
      return 2;
    }
  }
  if (image.empty() || out.empty() || files < 1) {
    std::fprintf(stderr,
                 "usage: recomp_lift_ppc --image module --out dir [--files N] [--forms dir]\n");
    return 2;
  }
  lifter::ppc::Program p;
  std::string err;
  if (!p.Load(image, err)) {
    std::fprintf(stderr, "recomp_lift_ppc: %s\n", err.c_str());
    return 1;
  }
  p.Discover();

  // Contiguous runs of functions, balanced by instruction count.
  size_t total = 0, invalid = 0, tables = 0, imports = 0;
  for (const auto& [va, f] : p.functions()) {
    total += f.insns.size();
    tables += f.tables.size();
    imports += f.import != nullptr;
    for (const auto& [iva, i] : f.insns)
      if (i.op == Op::kInvalid) {
        invalid++;
        std::fprintf(stderr, "recomp_lift_ppc: undecoded instruction %08X at %llX\n", i.raw,
                     static_cast<unsigned long long>(iva));
      }
  }
  std::vector<std::string> shard(files, kHeader);
  size_t done = 0;
  std::string decls, entries;
  for (const auto& [va, f] : p.functions()) {
    size_t k = std::min<size_t>(files - 1, done * files / std::max<size_t>(total, 1));
    shard[k] += lifter::ppc::EmitFunction(p, f);
    done += f.insns.size();
    std::string name = lifter::ppc::FunctionName(va);
    decls += "void " + name + "(Ctx& c);\n";
    char b[64];
    std::snprintf(b, sizeof b, "    {0x%08llXu, %s},\n", static_cast<unsigned long long>(va),
                  name.c_str());
    entries += b;
  }
  char hash[32];
  std::snprintf(hash, sizeof hash, "0x%llXull",
                static_cast<unsigned long long>(p.text_hash()));
  bool ok = true;
  for (int k = 0; k < files; k++) {
    char name[32];
    std::snprintf(name, sizeof name, "/funcs_%03d.cpp", k);
    ok = Write(out + name, shard[k] + "}  // namespace recomp::ppc\n") && ok;
  }
  ok = Write(out + "/table.cpp", kHeader + decls + "\nextern const LiftedFn kLiftedFunctions[] = {\n" +
                                     entries + "};\nextern const uint32_t kLiftedFunctionCount = " +
                                     std::to_string(p.functions().size()) +
                                     ";\nextern const uint64_t kLiftedTextHash = " + hash +
                                     ";\n\n}  // namespace recomp::ppc\n") &&
       ok;
  if (!forms.empty()) ok = WriteForms(p, forms) && ok;
  for (const std::string& w : p.warnings())
    std::fprintf(stderr, "recomp_lift_ppc: warning: %s\n", w.c_str());
  std::printf(
      "recomp_lift_ppc: %zu functions (%zu import thunks), %zu instructions, %zu jump tables, "
      "%zu undecoded\n",
      p.functions().size(), imports, total, tables, invalid);
  return ok ? 0 : 1;
}
